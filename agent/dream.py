def effects_of(option: "Option") -> tuple[Effect, ...]:
    """取一个选项的后果。

    数据里只有一个后果时写成了 (Effect(...))——单括号不是元组，
    拿到的是裸的 Effect。这里统一成元组，免得每处调用都要自己判断。
    """
    raw = option.effects
    if isinstance(raw, Effect):
        return (raw,)
    return tuple(raw or ())


def plan(chapter: Chapter) -> list[dict]:
    """把一章切成段落：段数 = 选择点数 + 1。

    返回 [{index, text, node}]，其中 node 是这一段之后要做的选择（最后一段为 None）。
    """
    body = text_source.combined_text(chapter.numbers)
    cuts: list[int] = []
    cursor = 0
    for node in chapter.nodes:
        found = body.find(node.marker, cursor)
        if found < 0:  # 锚句找不到（或落在已切过的位置）：留出等长的一段，绝不切出空段
            found = min(len(body), cursor + max(1, len(body) // (len(chapter.nodes) + 1)))
        cuts.append(found)
        cursor = found + 1

    segments: list[dict] = []
    start = 0
    for index, node in enumerate(chapter.nodes):
        end = cuts[index]
        segments.append({"index": index, "text": body[start:end].strip(), "node": node})
        start = end
    segments.append({"index": len(chapter.nodes), "text": body[start:].strip(), "node": None})
    return segments


def chapter_summary(chapter: Chapter) -> dict:
    return {
        "key": chapter.key,
        "title": chapter.title,
        "chapters": chapter.chapter_label,
        "cast": list(chapter.cast),
        "invoker": chapter.invoker,
        "node_count": len(chapter.nodes),
        "segment_count": len(chapter.nodes) + 1,
    }
