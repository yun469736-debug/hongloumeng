import type { Character, CharacterState, MotionPreset, PortraitAlignment } from '../types'

type StateSeed = [
  id: string,
  file: string,
  emotions: string[],
  actions: string[],
  intensity: number,
  motion: MotionPreset,
  stageDirection: string,
  alignment?: Partial<PortraitAlignment>,
]

const defaultAlignment: PortraitAlignment = { scale: 1, offsetX: 0, offsetY: 0 }

const labelOverrides: Record<string, string> = {
  '林黛玉:tearful-touch': '含泪拭面',
  '林黛玉:hesitant-hand': '掩唇迟疑',
  '林黛玉:cheek-pensive': '托腮沉思',
  '林黛玉:side-pensive': '侧眸惆怅',
  '林黛玉:tearful-handkerchief': '执帕含泪',
  '林黛玉:quiet-hesitation': '回眸迟疑',
  '林黛玉:flower-pensive': '捧花幽思',
  '林黛玉:sleeve-tears': '掩袖落泪',
  '林黛玉:purple-tears': '侧身拭泪',
  '林黛玉:soft-tears': '低眉伤感',
}

function makeState(name: string, seed: StateSeed): CharacterState {
  const [id, file, emotions, actions, intensity, motion, stageDirection, alignment] = seed
  return {
    id,
    label: labelOverrides[`${name}:${id}`] ?? file.replace(/\.png$/i, '').replace(name, '').replace(/^-/, ''),
    sourceFile: `素材/红楼梦/${name}/${file}`,
    image: `/assets/characters-webp/${name}/${file.replace(/\.png$/i, '.webp')}`,
    emotions,
    actions,
    intensity,
    motion,
    stageDirection,
    alignment: { ...defaultAlignment, ...alignment },
  }
}

function makeCharacter(
  id: string,
  name: string,
  courtesy: string,
  quote: string,
  defaultStateId: string,
  seeds: StateSeed[],
): Character {
  return { id, name, courtesy, quote, defaultStateId, available: true, states: seeds.map(seed => makeState(name, seed)) }
}

